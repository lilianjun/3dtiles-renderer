// P26: toggle the default procedural IBL. Cheap: only attaches/detaches the
// IndirectLight built once at initialize(); the cubemap and SH survive the
// session. No-op when IBL failed to build (sun-only fallback).
void Renderer::setIblEnabled(bool enabled) {
    if (!g_initialized) {
        return;
    }
#ifdef TILES_WITH_FILAMENT
    if (g_state.ibl == nullptr || g_state.scene == nullptr) {
        return;
    }
    if (g_state.iblEnabled == enabled) {
        return;
    }
    g_state.iblEnabled = enabled;
    g_state.scene->setIndirectLight(enabled ? g_state.ibl : nullptr);
    std::cout << "[tiles_renderer] IBL " << (enabled ? "enabled" : "disabled")
              << std::endl;
#else
    (void)enabled;
#endif
}

