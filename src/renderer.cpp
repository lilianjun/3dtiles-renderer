bool Renderer::loadTileset(const std::string& tilesetUrl,
                           const TilesetOptions& options) {
    if (!g_initialized) {
        setLastError("loadTileset: not initialized");
        return false;
    }
    setLastError("");
#ifdef TILES_WITH_FILAMENT
    FilamentState& s = g_state;
    if (s.engine == nullptr || s.scene == nullptr) {
        setLastError("loadTileset: engine not ready");
        return false;
    }
    auto tileset = std::make_unique<TilesetRenderer>(s.engine, s.scene);
    // P19: apply a budget set before load (no-op when never set).
    tileset->setMaxCachedBytes(g_pendingMaxCachedBytes);
    // P31: apply a pending live SSE override (no-op when never set).
    if (g_hasPendingMaxSse) {
        tileset->setMaximumScreenSpaceError(g_pendingMaxSse);
    }
    // P32: event callbacks persist across loads; the new TilesetRenderer
    // gets the current set before loading.
    tileset->setEventCallbacks(g_eventCallbacks);
    // P33: show / preloadWhenHidden / modelMatrix persist across loads;
    // the new TilesetRenderer gets the current values before loading.
    tileset->setShow(g_show);
    tileset->setPreloadWhenHidden(g_preloadWhenHidden);
    tileset->setModelMatrix(g_modelMatrix);
    tileset->setEnableShowOutline(g_enableShowOutline);
    tileset->setShowOutline(g_showOutline);
    tileset->setOutlineColor(
        g_outlineColor[0], g_outlineColor[1], g_outlineColor[2]);
    tileset->setDebugShowBoundingVolume(g_debugShowBoundingVolume);
    tileset->setDebugShowContentBoundingVolume(
        g_debugShowContentBoundingVolume);
    tileset->setDebugShowViewerRequestVolume(
        g_debugShowViewerRequestVolume);
    tileset->setDebugFreezeFrame(g_debugFreezeFrame);
    tileset->setDebugShowUrl(g_debugShowUrl);
    // P22: build-then-commit. The new TilesetRenderer is fully loaded
    // before it replaces the old one, so a failed loadTileset() (bad
    // path, corrupt tileset.json, timeout) leaves the currently-loaded
    // tileset untouched and rendering. The old code reset s.tileset up
    // front, destroying the working tileset even when the new load failed.
    if (!tileset->load(tilesetUrl, options)) {
        setLastError("loadTileset: " + tileset->lastError());
        return false;
    }
    // P32: the old tileset's content is released by the replacement below;
    // fire tileUnload for its loaded tiles first (synchronously, on the
    // render thread). Only on success — a failed load leaves the old
    // tileset untouched, so no unload events.
    if (s.tileset) {
        s.tileset->fireTileUnloadEvents();
    }
    s.tileset.reset(); // drop the previous tileset only on success
    s.tileset = std::move(tileset);
    return true;
#else
    (void)tilesetUrl;
    setLastError("loadTileset: not available in this build");
    return false;
#endif
}

bool Renderer::resize(std::uint32_t width, std::uint32_t height) {
    if (!g_initialized) {
        setLastError("resize: not initialized");
        return false;
    }
    if (width == 0 || height == 0) {
        setLastError("resize: dimensions must be nonzero");
        return false;
    }
    setLastError("");
#ifdef TILES_WITH_FILAMENT
    FilamentState& s = g_state;
    if (s.engine == nullptr || s.swapChain == nullptr ||
        s.nativeWindow == nullptr) {
        setLastError("resize: engine not ready");
        return false;
    }
    if (width == s.width && height == s.height) {
        return true; // no-op
    }
    // Recreate the swap chain for the same native window (the host owns the
    // window and is responsible for resizing the OS-level surface first).
    // Called between frames on the render thread, so no in-flight frame is
    // using the old swap chain.
    s.engine->destroy(s.swapChain);
    s.swapChain = s.engine->createSwapChain(s.nativeWindow);
    if (s.swapChain == nullptr) {
        setLastError("resize: createSwapChain failed");
        return false;
    }
    s.width = width;
    s.height = height;
    s.view->setViewport(filament::Viewport{0, 0, width, height});
    const double aspect = static_cast<double>(width) / static_cast<double>(height);
    // P37-C1: use saved FOV (not hardcoded 45°) so setFovDegrees() survives resize.
    s.camera->setProjection(s.fovDegrees, aspect, s.nearPlane, s.farPlane);
    std::cout << "[tiles_renderer] resized to " << width << "x" << height
              << std::endl;
    return true;
#else
    return true; // stub path: nothing to resize
#endif
}

